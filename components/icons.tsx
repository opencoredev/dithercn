export const getIconForLanguageExtension = (language: string) => {
  switch (language) {
    case "json": {
      return <JsonIcon />;
    }
    case "css": {
      return <CssIcon />;
    }
    case "js":
    case "jsx":
    case "ts":
    case "tsx":
    case "typescript": {
      return <TsIcon />;
    }
    default: {
      return <Icon icon={File01Icon} className="size-4" />;
    }
  }
};

export const getIconForPackageManager = (manager: PackageManager) => {
  switch (manager) {
    case "pnpm": {
      return <PnpmIcon />;
    }
    case "yarn": {
      return <YarnIcon />;
    }
    case "npm": {
      return <NpmIcon />;
    }
    case "bun": {
      return <BunIcon />;
    }
    default: {
      return <Icon icon={ComputerTerminal01Icon} />;
    }
  }
};
