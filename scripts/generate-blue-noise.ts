/**
 * Generates the 64x64 blue-noise threshold map embedded in
 * lib/dither/blue-noise.ts, using Ulichney's void-and-cluster method.
 *
 * Run with `node scripts/generate-blue-noise.ts > lib/dither/blue-noise.ts`.
 * The output is deterministic: the initial pattern comes from a seeded PRNG.
 */

const SIZE = 64;
const AREA = SIZE * SIZE;
const SIGMA = 1.5;
const INITIAL_DENSITY = 0.1;

// Mulberry32: small, seeded, good enough for the initial scatter.
/* oxlint-disable no-bitwise, unicorn/prefer-math-trunc -- a 32-bit PRNG */
const random = (() => {
  let seed = 2_654_435_769;
  return () => {
    seed = Math.trunc(seed + 1_831_565_813);
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
})();
/* oxlint-enable no-bitwise, unicorn/prefer-math-trunc */

// Toroidal Gaussian weights, indexed by wrapped (dx, dy).
const kernel = new Float64Array(AREA);
for (let dy = 0; dy < SIZE; dy += 1) {
  for (let dx = 0; dx < SIZE; dx += 1) {
    const x = Math.min(dx, SIZE - dx);
    const y = Math.min(dy, SIZE - dy);
    kernel[dy * SIZE + dx] = Math.exp(-(x * x + y * y) / (2 * SIGMA * SIGMA));
  }
}

const addEnergy = (energy: Float64Array, index: number, sign: number) => {
  const px = index % SIZE;
  const py = Math.floor(index / SIZE);
  for (let y = 0; y < SIZE; y += 1) {
    const dy = (y - py + SIZE) % SIZE;
    for (let x = 0; x < SIZE; x += 1) {
      const dx = (x - px + SIZE) % SIZE;
      energy[y * SIZE + x] += sign * (kernel[dy * SIZE + dx] ?? 0);
    }
  }
};

const extreme = (
  energy: Float64Array,
  pattern: Uint8Array,
  want: 0 | 1,
  pickMax: boolean
) => {
  let best = -1;
  let bestValue = pickMax ? -Infinity : Infinity;
  for (let i = 0; i < AREA; i += 1) {
    if (pattern[i] !== want) {
      continue;
    }
    const value = energy[i] ?? 0;
    if (pickMax ? value > bestValue : value < bestValue) {
      bestValue = value;
      best = i;
    }
  }
  return best;
};

const pattern = new Uint8Array(AREA);
const energy = new Float64Array(AREA);
const initialCount = Math.round(AREA * INITIAL_DENSITY);
for (let placed = 0; placed < initialCount; ) {
  const index = Math.floor(random() * AREA);
  if (pattern[index] === 0) {
    pattern[index] = 1;
    addEnergy(energy, index, 1);
    placed += 1;
  }
}

// Relax: move the tightest cluster into the largest void until stable.
for (;;) {
  const cluster = extreme(energy, pattern, 1, true);
  pattern[cluster] = 0;
  addEnergy(energy, cluster, -1);
  const gap = extreme(energy, pattern, 0, false);
  pattern[gap] = 1;
  addEnergy(energy, gap, 1);
  if (gap === cluster) {
    break;
  }
}

const ranks = new Uint16Array(AREA);
const initial = [...pattern];
const initialEnergy = [...energy];

// Phase 1: remove clusters from the initial pattern, ranking downwards.
let rank = initialCount - 1;
while (rank >= 0) {
  const cluster = extreme(energy, pattern, 1, true);
  pattern[cluster] = 0;
  addEnergy(energy, cluster, -1);
  ranks[cluster] = rank;
  rank -= 1;
}

// Phases 2 and 3: fill voids from the initial pattern, ranking upwards.
pattern.set(initial);
energy.set(initialEnergy);
for (rank = initialCount; rank < AREA; rank += 1) {
  const gap = extreme(energy, pattern, 0, false);
  pattern[gap] = 1;
  addEnergy(energy, gap, 1);
  ranks[gap] = rank;
}

// 4096 ranks squeezed into 256 levels, 16 cells per level: plenty for
// thresholding, and one byte per cell.
const bytes = Buffer.from(Array.from(ranks, (value) => Math.floor(value / 16)));
const encoded = bytes.toString("base64");
const lines = encoded.match(/.{1,76}/g) ?? [];

process.stdout
  .write(`// Generated by scripts/generate-blue-noise.ts. Do not edit by hand.
// 64x64 void-and-cluster blue noise, one byte per cell (rank / 16), base64.
export const BLUE_NOISE_64_BASE64 =
${lines.map((line) => `  "${line}"`).join(" +\n")};
`);
